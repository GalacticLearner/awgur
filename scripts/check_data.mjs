import { readFileSync, readdirSync, statSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import assert from 'node:assert/strict';
const files=['works','requests','ground_truth','fixtures','demo'];
const before=files.map(n=>readFileSync(`public/data/${n}.json`));
const regenerated=spawnSync(process.platform==='win32'?'npm.cmd':'npm',['run','seed'],{stdio:'inherit',shell:process.platform==='win32'});
assert.equal(regenerated.status,0);
assert.ok(files.every((n,i)=>before[i].equals(readFileSync(`public/data/${n}.json`))),'Seed output changed');
const read=n=>JSON.parse(readFileSync(`public/data/${n}.json`));
const segments=read('segments'),works=read('works'),fixtures=read('fixtures'),cases=read('ground_truth');
assert.equal(works.length,128);assert.equal(read('requests').length,6);assert.equal(cases.length,76);
const expected={r1_positive:12,r1_negative:12,r1_emergency:4,r2_positive:12,r2_negative:16,r3_positive:12,r3_negative:8};
for(const [category,count] of Object.entries(expected))assert.equal(cases.filter(c=>c.category===category).length,count);
const ids=new Set(segments.map(s=>s.id));
for(const record of [...works,...fixtures,...read('requests'),...cases.map(c=>c.request)])assert.ok(record.segmentIds.every(id=>ids.has(id)),'Unknown segment in '+record.id);
const fixtureIds=new Set(fixtures.map(w=>w.id));
assert.ok(cases.every(c=>c.existingWorkIds.every(id=>fixtureIds.has(id))));
assert.ok(readdirSync('public/data').reduce((sum,n)=>sum+statSync(`public/data/${n}`).size,0)<3*1024*1024);
console.log('Data counts, references, size and byte-for-byte determinism passed.');
